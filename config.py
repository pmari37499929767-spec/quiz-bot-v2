@dataclass
class ResultButton:
    """Кнопка для результата"""
    id: str          # callback_data для кнопки
    text: str        # Текст кнопки (может содержать {ЭКСПЕРТ})
    url: str = None  # URL для внешней ссылки (если указан, кнопка будет ссылкой)


@dataclass
class ResultSeries:
    """Серия результатов для конкретной зоны"""
    series_id: str              # ID серии (S1, S2, etc)
    title_internal: str         # Внутреннее название для администратора
    result_tag: str             # Тег зоны: PRODUCT, TRAFFIC, CONTENT, SALES, SYSTEM
    variables: List[str]        # Переменные для подстановки
    message_twist: str          # Текст с TWIST (когда perceived != bottleneck)
    message_confirmation: str   # Текст подтверждения (когда perceived == bottleneck)
    buttons: List[ResultButton] # Кнопки для действий


